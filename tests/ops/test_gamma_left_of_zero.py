def _values(function, points, dtype="float64"):
    x = np.array([p for p, _ in points], dtype=dtype)
    return getattr(mt, function)(mt.tensor(x)).numpy()


@pytest.mark.parametrize(
    "function,points",
    [("lgamma", LGAMMA_POINTS), ("digamma", DIGAMMA_POINTS)],
)
def test_the_float_nearest_the_exact_value(function, points):
    got = _values(function, points)
    want = np.array([w for _, w in points])
    np.testing.assert_array_equal(got, want)


@pytest.mark.parametrize(
    "function,points",
    [("lgamma", LGAMMA_NEAR_ZEROS), ("digamma", DIGAMMA_NEAR_ZEROS)],
)
def test_the_floats_either_side_of_each_zero_keep_their_digits(function, points):
    # The float nearest each zero and its neighbours, where the answer is as
    # small as 5.6e-17 against terms of size one: what float64 left of it
    # was its first digit, or not even that.
    got = _values(function, points)
    want = np.array([w for _, w in points])
    np.testing.assert_allclose(got, want, rtol=2e-14, atol=0)


@pytest.mark.parametrize(
    "function,points",
    [("lgamma", LGAMMA_POINTS), ("digamma", DIGAMMA_POINTS)],
)
def test_float32_rounds_the_same_values(function, points):
    # A float32 argument is the same number in float64; its answer is the
    # float64 one rounded once more, within one float32 ulp of the exact.
    x = np.array([p for p, _ in points], dtype=np.float32)
    got = getattr(mt, function)(mt.tensor(x)).numpy()
    want = getattr(mt, function)(mt.tensor(x.astype(np.float64))).numpy()
    np.testing.assert_array_equal(got, want.astype(np.float32))


def test_lgamma_differentiates_to_digamma_left_of_zero():
    x = mt.tensor(np.array([-2.5, -3.25, -7.75, -0.5]), requires_grad=True)
    mt.lgamma(x).sum().backward()
    np.testing.assert_array_equal(x.grad.numpy(), mt.digamma(x.detach()).numpy())
